/** Доступ к файлам раздела без регистрации (через svedeniya/index.php?file=…) */
function svedFile(string $name): void {
    $base = realpath(dirname(__DIR__) . '/uploads/documents');
    $path = $base ? realpath($base . '/' . basename($name)) : false;
    if (!$path || !is_file($path) || strpos($path, $base) !== 0) {
        http_response_code(404);
        exit('Файл не найден.');
    }
    $mimeMap = [
        'pdf' => 'application/pdf', 'doc' => 'application/msword',
        'docx' => 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
        'xls' => 'application/vnd.ms-excel',
        'xlsx' => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
        'txt' => 'text/plain; charset=UTF-8', 'rtf' => 'application/rtf',
        'odt' => 'application/vnd.oasis.opendocument.text',
        'jpg' => 'image/jpeg', 'jpeg' => 'image/jpeg', 'png' => 'image/png',
    ];
    $ext = strtolower(pathinfo($path, PATHINFO_EXTENSION));
    header('Content-Type: ' . ($mimeMap[$ext] ?? 'application/octet-stream'));
    header('Content-Length: ' . filesize($path));
    header('Content-Disposition: inline; filename="' . rawurlencode(basename($path)) . '"');
    readfile($path);
    exit;
}

/** Ссылка на файл раздела с пояснением о его назначении (п.4 Требований) */
function svedDocLink(string $title, string $file, string $note = ''): string {
    $href = '/svedeniya/?file=' . rawurlencode($file);
    $label = '<span class="sved-file__name">' . e($title) . '</span>';
    $meta = [];
    $full = dirname(__DIR__) . '/uploads/documents/' . $file;
    if (is_file($full)) {
        $meta[] = strtoupper(pathinfo($file, PATHINFO_EXTENSION)) . ', '
                . round(filesize($full) / 1024) . ' КБ';
    } else {
        $meta[] = 'PDF';
    }
    return '<a class="sved-file" href="' . e($href) . '" target="_blank" rel="noopener"'
         . ' data-sved-doc-title="' . e($title) . '"'
         . ' data-sved-doc-format="' . e(strtolower(pathinfo($file, PATHINFO_EXTENSION) ?: 'pdf')) . '">'
         . '<span class="sved-file__icon" aria-hidden="true">📄</span>'
         . '<span>' . $label
         . '<span class="sved-file__meta">' . e(implode(' · ', $meta))
         . ($note !== '' ? ' · ' . e($note) : '') . '</span></span></a>';
}

/** Иерархический список подразделов — механизм навигации на каждой странице раздела (п.2) */
function svedNav(): void {
    global $SVOD, $sub;
    $sub = $sub ?? '';
    echo '<ul class="sved-nav__list">';
    foreach ($SVOD as $slug => $s) {
        $active = $slug === $sub ? ' class="active"' : '';
        echo '<li><a href="/svedeniya/?sub=' . e($slug) . '"' . $active
           . ' data-sved-page="' . e($slug) . '">' . e($s['title']) . '</a></li>';
    }
    echo '</ul>';
}

